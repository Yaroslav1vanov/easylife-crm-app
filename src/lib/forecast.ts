export const UNPACK_FIELDS = UNPACK_GROUPS.flatMap(g => g.fields);
export type Unpacking = Record<string, string>;

/** Распаковка текстом — для ИИ и для истории версий. Пустые поля явно помечены. */
export function unpackingToText(d: Unpacking): string {
  return UNPACK_GROUPS.map(g => `## ${g.title}\n` + g.fields.map(f => {
    const v = (d[f.id] || "").trim();
    return `- ${f.label}: ${v || "— НЕ ЗАПОЛНЕНО —"}`;
  }).join("\n")).join("\n\n");
}
export const filledCount = (d: Unpacking) => UNPACK_FIELDS.filter(f => (d[f.id] || "").trim()).length;

