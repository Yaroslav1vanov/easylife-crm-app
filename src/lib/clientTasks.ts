/** Даты задач по клиенту. Возвращает список «что и когда» в горизонте [fromDate, toDate]. */
export function plannedTasks(args: {
  today: string;
  horizonDays: number;
  backfillDays: number;
  monthNumber: number | null;
  monthStart: string | null;
  monthEnd: string | null;
  firstPublishDate: string | null;   // когда реально начались публикации
  hasMetricool: boolean;
}): { kind: TaskKind; due: string; weekFrom?: string; weekTo?: string }[] {
  const { today, horizonDays, backfillDays } = args;
  const from = shift(today, -backfillDays), to = shift(today, horizonDays);
  const inRange = (d: string) => d >= from && d <= to;
  const out: { kind: TaskKind; due: string; weekFrom?: string; weekTo?: string }[] = [];

  // разговор на 15-й день после старта публикаций — только в первом месяце
  if (args.monthNumber === 1 && args.firstPublishDate) {
    const due = shift(args.firstPublishDate, 14);
    if (inRange(due)) out.push({ kind: "talk_day15", due });
  }
  // недельный отчёт — каждую пятницу за прошлую полную неделю
  if (args.hasMetricool && args.firstPublishDate) {
    for (let d = from; d <= to; d = shift(d, 1)) {
      if (new Date(d + "T00:00:00Z").getUTCDay() !== 5) continue;   // пятница
      const weekTo = shift(d, -(((new Date(d + "T00:00:00Z").getUTCDay() + 6) % 7) + 1));  // прошлое воскресенье
      const weekFrom = shift(weekTo, -6);
      if (weekTo < args.firstPublishDate) continue;
      out.push({ kind: "weekly_report", due: d, weekFrom, weekTo });
    }
  }
  if (args.monthEnd) {
    const notice = shift(args.monthEnd, -6), check = shift(args.monthEnd, -2), review = shift(args.monthEnd, 1);
    if (inRange(notice)) out.push({ kind: "payment_notice", due: notice });
    if (inRange(check)) out.push({ kind: "payment_check", due: check });
    if (inRange(review)) out.push({ kind: "month_review", due: review });
  }
  return out;
}

export function shift(iso: string, n: number): string {
  const d = new Date(iso + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}
