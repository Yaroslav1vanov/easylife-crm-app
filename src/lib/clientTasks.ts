// Задачи проджекта по клиенту: что и когда он делает по каждому клиенту.
// Тексты — готовые инструкции, чтобы проджект мог действовать без дополнительных вопросов.
// С клиентами говорим на «вы».

export type TaskKind = "talk_day15" | "weekly_report" | "payment_notice" | "payment_check" | "month_review";

export const TASK_META: Record<TaskKind, { label: string; color: string; icon: string }> = {
  talk_day15:     { label: "Разговор 15-й день", color: "#a8e063", icon: "🗣" },
  weekly_report:  { label: "Недельный отчёт",    color: "#42d4f4", icon: "📊" },
  payment_notice: { label: "Оплата заранее",     color: "#ffae42", icon: "💳" },
  payment_check:  { label: "Контроль оплаты",    color: "#ff5c7a", icon: "⏰" },
  month_review:   { label: "Итоги месяца",       color: "#9d6bff", icon: "🧾" },
};

const dm = (iso: string) => `${iso.slice(8, 10)}.${iso.slice(5, 7)}`;

export function taskTitle(kind: TaskKind, ctx: { clientName: string; monthNumber?: number | null; endDate?: string | null; weekFrom?: string; weekTo?: string }): string {
  switch (kind) {
    case "talk_day15": return `Разговор на 15-й день: как идёт и продать второй месяц`;
    case "weekly_report": return `Недельный отчёт клиенту за ${ctx.weekFrom ? dm(ctx.weekFrom) : ""}–${ctx.weekTo ? dm(ctx.weekTo) : ""}`;
    case "payment_notice": return `Написать про оплату следующего месяца (месяц до ${ctx.endDate ? dm(ctx.endDate) : "—"})`;
    case "payment_check": return `Проверить оплату и напомнить, если не пришла`;
    case "month_review": return `Итоги месяца M${ctx.monthNumber ?? "?"} и план следующего`;
  }
}

